import { assert, assertEquals, assertStringIncludes } from "./assert.ts";
import { companyPath, type CrmContext, dealPath, renderCompany, renderContacts, renderPipeline } from "../para/crm.ts";

const now = new Date("2026-11-19T12:00:00Z");
const x = (over: Partial<CrmContext> = {}): CrmContext => ({ folder: "CRM", now, archiveAfterDays: 30, contactDetails: false, recordPath: () => undefined, ...over });
const company = { id: "11111111-aaaa-bbbb-cccc-000000000001", name: "Acme Dental", lifecycle: "client", domain: "acmedental.com", tags: [], screen_status: "not_needed", archived_at: null, updated_at: now };
const deal = (over: Record<string, unknown> = {}) => ({
  id: "22222222-aaaa-bbbb-cccc-000000000002", name: "Intake automation", company_id: company.id, company_name: "Acme Dental", stage: "proposal", stage_name: "Proposal",
  is_won: false, is_lost: false, amount: "12500.00", recurring_monthly: "1500.00", currency: "USD", probability: 60, closed_at: null, archived_at: null,
  last_activity_at: "2026-11-18T00:00:00Z", created_at: "2026-11-01T00:00:00Z", updated_at: now, tags: [], ...over,
});
const dana = { id: "c1", full_name: "Dana Ortiz", job_title: "Practice manager", email: "dana@acmedental.com", phone: "555-0100", consent: "opted_in", do_not_contact: false, company_id: company.id, archived_at: null };

Deno.test("CRM pages live under 2-Areas/CRM; disqualified companies and long-closed deals move to the archive", () => {
  assertEquals(companyPath(company, x()), "2-Areas/CRM/Companies/Acme Dental (11111111).md");
  assertEquals(companyPath({ ...company, lifecycle: "disqualified" }, x()), "4-Archive/CRM/Companies/Acme Dental (11111111).md");
  assertEquals(dealPath(deal(), x()), "2-Areas/CRM/Deals/Intake automation (22222222).md");
  assertEquals(dealPath(deal({ is_won: true, closed_at: "2026-11-01T00:00:00Z" }), x()).split("/")[0], "2-Areas");
  assertEquals(dealPath(deal({ is_lost: true, closed_at: "2026-09-01T00:00:00Z" }), x()).split("/")[0], "4-Archive");
  assertEquals(companyPath(company, x({ folder: "Sales/CRM" })).split("/")[1], "Sales CRM");
});

Deno.test("contact emails and phones stay out of the mirror unless enabled", () => {
  const hidden = renderCompany(company, [dana], [deal()], [], x());
  assert(!hidden.includes("dana@acmedental.com") && !hidden.includes("555-0100"));
  assertStringIncludes(hidden, "email on file");
  const shown = renderCompany(company, [dana], [deal()], [], x({ contactDetails: true }));
  assertStringIncludes(shown, "dana@acmedental.com");
  const list = renderContacts([dana], new Map([[company.id, company]]), x());
  assert(!list.includes("dana@acmedental.com"));
  assertStringIncludes(list, "kept in OpsBrain");
});

Deno.test("pipeline page totals, weighting and stale flags", () => {
  const stages = [
    { slug: "proposal", name: "Proposal", is_won: false, is_lost: false },
    { slug: "won", name: "Won", is_won: true, is_lost: false },
  ];
  const md = renderPipeline(stages, [deal(), deal({ id: "33333333-aaaa-bbbb-cccc-000000000003", name: "Old one", amount: "1000", last_activity_at: "2026-10-01T00:00:00Z" })], new Map([[company.id, company]]), x());
  assertStringIncludes(md, "2 open deals · $13,500 open value · $8,100 weighted");
  assertStringIncludes(md, "(stale)");
  assertStringIncludes(md, "](Deals/Intake%20automation%20(22222222).md)");
  assert(md.includes("<!-- Generated by OpsBrain"));
});
