// PARA placement and Markdown rendering for the human-readable OpsBrain mirror.
// Pure functions (no database, no file system) so the rules are easy to test.
//
//   1-Projects/<project>/<record type>/   records of active projects and client engagements
//   2-Areas/<area>/<record type>/         ongoing responsibilities (sales, delivery, finance...)
//   3-Resources/<topic>/                  playbooks, SOPs, templates, research, references, policies
//   4-Archive/{Projects,Areas,Resources}/ completed projects, archived records, stale finished work

export type ExportRecord = {
  id: string; record_type: string; record_type_name: string; type_folder: string;
  para_default: "project" | "area" | "resource"; terminal_statuses: string[];
  title: string | null; content: string; status: string | null; external_ref: string | null;
  project_id: string | null; project_name: string | null; project_kind: string | null; project_status: string | null;
  client_name: string | null; area_slug: string | null; area_name: string | null;
  process_id: string | null; process_name: string | null; process_step: number | null;
  para_override: "project" | "area" | "resource" | "archive" | null; resource_topic: string | null;
  priority: string | null; due_on: string | Date | null; tags: string[]; fields: Record<string, unknown>;
  visibility: string; financial_or_ethical: boolean; requires_approval: boolean; approval_status: string | null;
  approved_by: string | null; approved_at: string | Date | null; version: number;
  archived_at: string | Date | null; created_at: string | Date; updated_at: string | Date;
  owner: string | null; assignee: string | null; created_by: string | null; updated_by: string | null;
  authenticated_as: string | null; on_behalf_of: string | null;
};

export type ProjectInfo = {
  id: string; name: string; kind: string; client_name: string | null; status: string; area_slug: string | null;
  owner: string | null; started_on: string | Date | null; due_on: string | Date | null; completed_on: string | Date | null; description: string | null;
};

export type HistoryEntry = { created_at: string | Date; actor: string | null; action: string; comment: string | null };
export type LinkEntry = { relation: string; direction: "outgoing" | "incoming"; id: string; title: string | null };

export const MARKER = "<!-- Generated by OpsBrain. Edit the record in OpsBrain; changes made to this file are overwritten. -->";
export const ROOTS = { project: "1-Projects", area: "2-Areas", resource: "3-Resources", archive: "4-Archive" } as const;
const CLOSED_PROJECT = new Set(["completed", "cancelled"]);

export function safeName(s: string, max = 80): string {
  const cleaned = s
    .normalize("NFKD").replace(/[̀-ͯ]/g, "")
    .replace(/[\\/:*?"<>|#^[\]\n\r\t]+/g, " ")
    .replace(/(^|\s)\.+(?=\s|$)/g, " ")
    .replace(/\s+/g, " ").trim().replace(/^\.+/, "");
  return (cleaned.slice(0, max).trim() || "Untitled");
}

function iso(d: string | Date | null | undefined): string {
  if (!d) return "";
  return (d instanceof Date ? d : new Date(d)).toISOString();
}

function day(d: string | Date | null | undefined): string {
  return iso(d).slice(0, 10);
}

export function projectFolder(id: string, name: string | null): string {
  return safeName(`${id} - ${name ?? id}`, 90);
}

export type Placement = { bucket: keyof typeof ROOTS; dir: string[] };

/** Decide which PARA folder a record belongs in. */
export function placeRecord(r: ExportRecord, now: Date, archiveAfterDays: number): Placement {
  const proj = r.project_id ? projectFolder(r.project_id, r.project_name) : null;
  const area = safeName(r.area_name ?? "General");
  const topic = safeName(r.resource_topic ?? r.tags?.[0] ?? r.type_folder);
  const finished = r.status !== null && r.terminal_statuses.includes(r.status);
  const ageDays = (now.getTime() - new Date(r.updated_at).getTime()) / 86_400_000;
  const projectClosed = r.project_status !== null && CLOSED_PROJECT.has(r.project_status);

  let bucket: Placement["bucket"];
  if (r.para_override) bucket = r.para_override;
  else if (r.archived_at || projectClosed) bucket = "archive";
  else if (r.project_id) bucket = "project";
  else if (r.para_default === "resource") bucket = "resource";
  else if (finished && ageDays > archiveAfterDays) bucket = "archive";
  else bucket = "area";

  switch (bucket) {
    case "project":
      return { bucket, dir: [ROOTS.project, proj ?? "No project", r.type_folder] };
    case "resource":
      return { bucket, dir: [ROOTS.resource, topic] };
    case "area":
      return { bucket, dir: [ROOTS.area, area, r.type_folder] };
    case "archive":
      if (proj) return { bucket, dir: [ROOTS.archive, "Projects", proj, r.type_folder] };
      if (r.para_default === "resource") return { bucket, dir: [ROOTS.archive, "Resources", topic] };
      return { bucket, dir: [ROOTS.archive, "Areas", area, r.type_folder] };
  }
}

export function fileName(r: ExportRecord): string {
  const label = r.title?.trim() || r.content.split("\n").find((l) => l.trim())?.replace(/^#+\s*/, "") || r.record_type_name;
  return `${day(r.created_at)} ${safeName(label, 70)} (${r.id.slice(0, 8)}).md`;
}

export function recordPath(r: ExportRecord, now: Date, archiveAfterDays: number): string {
  return [...placeRecord(r, now, archiveAfterDays).dir, fileName(r)].join("/");
}

function yamlValue(v: unknown): string {
  if (v === null || v === undefined || v === "") return "";
  if (Array.isArray(v)) return `[${v.map((x) => JSON.stringify(String(x))).join(", ")}]`;
  if (typeof v === "boolean" || typeof v === "number") return String(v);
  if (v instanceof Date) return v.toISOString();
  return JSON.stringify(String(v));
}

function cell(v: unknown): string {
  const s = typeof v === "string" ? v : JSON.stringify(v);
  return (s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
}

/** Relative Markdown link from one generated file to another. */
export function relLink(from: string, to: string): string {
  const a = from.split("/").slice(0, -1);
  const b = to.split("/");
  let i = 0;
  while (i < a.length && i < b.length - 1 && a[i] === b[i]) i++;
  const up = a.length - i;
  return [...Array(up).fill(".."), ...b.slice(i)].map(encodeURIComponent).join("/");
}

export function renderRecord(
  r: ExportRecord, path: string, history: HistoryEntry[], links: LinkEntry[], pathOf: (id: string) => string | undefined,
): string {
  const fm: [string, unknown][] = [
    ["id", r.id], ["type", r.record_type], ["title", r.title], ["status", r.status], ["external_ref", r.external_ref],
    ["project", r.project_id], ["client", r.client_name], ["area", r.area_slug], ["process", r.process_id],
    ["step", r.process_step], ["owner", r.owner], ["assignee", r.assignee], ["created_by", r.created_by],
    ["updated_by", r.updated_by], ["on_behalf_of", r.on_behalf_of], ["authenticated_as", r.authenticated_as],
    ["priority", r.priority], ["due", day(r.due_on)], ["tags", r.tags], ["visibility", r.visibility],
    ["financial_or_ethical", r.financial_or_ethical], ["approval", r.requires_approval ? r.approval_status : null],
    ["approved_by", r.approved_by], ["approved_at", iso(r.approved_at)], ["version", r.version],
    ["created", iso(r.created_at)], ["updated", iso(r.updated_at)], ["archived", iso(r.archived_at)],
  ];
  const lines: string[] = ["---"];
  for (const [k, v] of fm) {
    const y = yamlValue(v);
    if (y !== "" && y !== "[]") lines.push(`${k}: ${y}`);
  }
  lines.push("---", MARKER, "", `# ${r.title?.trim() || r.record_type_name}`, "");

  const facts: string[] = [`**${r.record_type_name}**`];
  if (r.status) facts.push(`status: ${r.status}`);
  if (r.requires_approval) facts.push(`approval: ${r.approval_status}${r.approved_by ? ` by ${r.approved_by}` : ""}`);
  if (r.owner) facts.push(`owner: ${r.owner}`);
  if (r.assignee) facts.push(`assignee: ${r.assignee}`);
  if (r.process_id) facts.push(`process: ${r.process_id}${r.process_step ? ` step ${r.process_step}` : ""}${r.process_name ? ` (${r.process_name})` : ""}`);
  lines.push(facts.join(" · "), "", r.content.trim(), "");

  const fieldEntries = Object.entries(r.fields ?? {});
  if (fieldEntries.length) {
    lines.push("## Fields", "", "| Field | Value |", "| --- | --- |");
    for (const [k, v] of fieldEntries) lines.push(`| ${cell(k)} | ${cell(v)} |`);
    lines.push("");
  }
  if (links.length) {
    lines.push("## Links", "");
    for (const l of links) {
      const target = pathOf(l.id);
      const label = l.title ?? l.id.slice(0, 8);
      const arrow = l.direction === "outgoing" ? `${l.relation} →` : `← ${l.relation}`;
      lines.push(`- ${arrow} ${target ? `[${label}](${relLink(path, target)})` : `${label} (not in this mirror)`}`);
    }
    lines.push("");
  }
  if (history.length) {
    lines.push("## History", "", "| When | Who | Action | Note |", "| --- | --- | --- | --- |");
    for (const h of history) lines.push(`| ${iso(h.created_at).slice(0, 16).replace("T", " ")} | ${cell(h.actor ?? "")} | ${h.action} | ${cell(h.comment ?? "")} |`);
    lines.push("");
  }
  return lines.join("\n");
}

export function renderProjectIndex(p: ProjectInfo, records: { path: string; r: ExportRecord }[], indexPath: string): string {
  const open = records.filter(({ r }) => !(r.status && r.terminal_statuses.includes(r.status)));
  const lines = [
    "---", `project: ${JSON.stringify(p.id)}`, `name: ${JSON.stringify(p.name)}`, `kind: ${p.kind}`, `status: ${p.status}`,
    ...(p.client_name ? [`client: ${JSON.stringify(p.client_name)}`] : []), ...(p.owner ? [`owner: ${p.owner}`] : []),
    "---", MARKER, "", `# ${p.id}: ${p.name}`, "",
    `**${p.kind === "client_engagement" ? "Client engagement" : "Internal project"}** · status: ${p.status}` +
      (p.owner ? ` · owner: ${p.owner}` : "") + (p.due_on ? ` · due: ${day(p.due_on)}` : ""),
    "", p.description ?? "", "",
    `## Open items (${open.length})`, "",
  ];
  if (open.length) {
    lines.push("| Record | Type | Status | Assignee | Updated |", "| --- | --- | --- | --- | --- |");
    for (const { path, r } of open.slice(0, 200)) {
      lines.push(`| [${cell(r.title ?? r.record_type_name)}](${relLink(indexPath, path)}) | ${r.record_type_name} | ${r.status ?? ""} | ${r.assignee ?? ""} | ${day(r.updated_at)} |`);
    }
  } else lines.push("Nothing open.");
  lines.push("", `All records: ${records.length}.`, "");
  return lines.join("\n");
}

export function renderAreaIndex(name: string, records: { path: string; r: ExportRecord }[], indexPath: string): string {
  const open = records.filter(({ r }) => !(r.status && r.terminal_statuses.includes(r.status)));
  const lines = ["---", `area: ${JSON.stringify(name)}`, "---", MARKER, "", `# ${name}`, "", `## Open items (${open.length})`, ""];
  if (open.length) {
    lines.push("| Record | Type | Status | Owner | Updated |", "| --- | --- | --- | --- | --- |");
    for (const { path, r } of open.slice(0, 200)) {
      lines.push(`| [${cell(r.title ?? r.record_type_name)}](${relLink(indexPath, path)}) | ${r.record_type_name} | ${r.status ?? ""} | ${r.owner ?? ""} | ${day(r.updated_at)} |`);
    }
  } else lines.push("Nothing open.");
  lines.push("", `All records: ${records.length}.`, "");
  return lines.join("\n");
}

export function renderRootIndex(opts: {
  title: string; exportedAt: Date; projects: { folder: string; p: ProjectInfo; count: number }[];
  areas: { folder: string; count: number }[]; pending: { path: string; r: ExportRecord }[];
  recent: { path: string; r: ExportRecord }[]; total: number;
  crm?: { pipeline: string; openDeals: number };
}): string {
  const l = [
    `# ${opts.title}`, "", MARKER, "",
    `Human-readable mirror of OpsBrain, organized with PARA (Projects, Areas, Resources, Archive). Last exported ${opts.exportedAt.toISOString().slice(0, 16).replace("T", " ")} UTC. ${opts.total} records.`,
    "", "**Edit records in OpsBrain, not here.** These files are regenerated on every export.", "",
    "## Active projects", "",
  ];
  const active = opts.projects.filter((x) => !CLOSED_PROJECT.has(x.p.status));
  if (active.length) for (const x of active) l.push(`- [${x.p.id}: ${x.p.name}](${encodeURI(`${ROOTS.project}/${x.folder}/_index.md`)}) · ${x.p.status} · ${x.count} records`);
  else l.push("None.");
  l.push("", "## Areas", "");
  if (opts.areas.length) for (const a of opts.areas) l.push(`- [${a.folder}](${encodeURI(`${ROOTS.area}/${a.folder}/_index.md`)}) · ${a.count} records`);
  else l.push("None.");
  if (opts.crm) l.push("", "## Sales", "", `- [Pipeline](${encodeURI(opts.crm.pipeline)}) · ${opts.crm.openDeals} open deals`);
  l.push("", `## Waiting for approval (${opts.pending.length})`, "");
  if (opts.pending.length) for (const { path, r } of opts.pending) l.push(`- [${r.title ?? r.record_type_name}](${encodeURI(path)}) · ${r.record_type_name} · owner ${r.owner ?? "none"}`);
  else l.push("Nothing waiting.");
  l.push("", "## Recently updated", "");
  for (const { path, r } of opts.recent) l.push(`- ${day(r.updated_at)} · [${r.title ?? r.record_type_name}](${encodeURI(path)}) · ${r.record_type_name}${r.updated_by ? ` · ${r.updated_by}` : ""}`);
  l.push("");
  return l.join("\n");
}
